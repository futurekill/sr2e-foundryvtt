#!/usr/bin/env node
/**
 * Combat sound effects (docs/PLAN-combat-sounds.md): tools/data/sfx.json →
 * assets/sfx/<key>.mp3 through the ElevenLabs sound-generation API
 * (ELEVENLABS_API_KEY), each loudness-normalised and encoded mono 96 kbps with
 * ffmpeg so the set is even and small. Existing files are kept: delete one to
 * regenerate it. Always rewrites module/sfx-manifest.mjs from the files present, so
 * the code only ever asks for sounds that ship.
 *   node tools/gen-sfx.mjs            # generate missing sounds, write the manifest
 *   node tools/gen-sfx.mjs --manifest # manifest only, no API calls
 *   node tools/gen-sfx.mjs --normalize # re-level every existing file, no API calls
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync, rmSync, renameSync } from "node:fs";
import { execFileSync, spawnSync } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "assets/sfx");
const { sounds } = JSON.parse(readFileSync(path.join(ROOT, "tools/data/sfx.json"), "utf8"));
const KEY = process.env.ELEVENLABS_API_KEY;
mkdirSync(OUT, { recursive: true });

/**
 * Level a clip to one loudness target. ffmpeg's one-pass loudnorm misjudges clips a
 * second or two long, so measure the clip's integrated loudness (EBU R128), apply
 * the exact gain to reach the target, and cap the peaks with a limiter.
 */
const TARGET_LUFS = -16;
function normalize(src, dest) {
  // ebur128 prints its summary on stderr; the last "I:" line is the integrated loudness.
  const { stderr } = spawnSync("ffmpeg", ["-hide_banner", "-nostats", "-i", src, "-af", "ebur128", "-f", "null", "-"], { encoding: "utf8" });
  const measured = parseFloat([...stderr.matchAll(/^\s+I:\s+(-?[\d.]+) LUFS/gm)].at(-1)?.[1]);
  const gain = Number.isFinite(measured) ? TARGET_LUFS - measured : 0;
  const tmp = `${dest}.tmp.mp3`;
  execFileSync("ffmpeg", ["-hide_banner", "-loglevel", "error", "-y", "-i", src,
    "-af", `volume=${gain.toFixed(2)}dB,alimiter=limit=0.84:level=false`, "-ac", "1", "-b:a", "96k", tmp]);
  renameSync(tmp, dest);
  return { measured, gain };
}

if (!process.argv.includes("--manifest") && !process.argv.includes("--normalize")) {
  if (!KEY) { console.error("ELEVENLABS_API_KEY is not set (or use --manifest)."); process.exit(1); }
  for (const [key, [text, seconds]] of Object.entries(sounds)) {
    const file = path.join(OUT, `${key}.mp3`);
    if (existsSync(file)) continue;
    const res = await fetch("https://api.elevenlabs.io/v1/sound-generation", {
      method: "POST", headers: { "xi-api-key": KEY, "Content-Type": "application/json" },
      body: JSON.stringify({ text, duration_seconds: Math.max(0.5, seconds), prompt_influence: 0.6 })
    });
    if (!res.ok) throw new Error(`${key}: HTTP ${res.status} ${(await res.text()).slice(0, 200)}`);
    const raw = path.join(OUT, `${key}.raw.mp3`);
    writeFileSync(raw, Buffer.from(await res.arrayBuffer()));
    // One loudness target for every sound, so a pistol isn't quieter than a grenade.
    normalize(raw, file);
    rmSync(raw);
    console.log(`  + ${key}`);
  }
}

if (process.argv.includes("--normalize")) {
  for (const f of readdirSync(OUT).filter(f => f.endsWith(".mp3"))) {
    const { measured, gain } = normalize(path.join(OUT, f), path.join(OUT, f));
    console.log(`  ${f.padEnd(24)} ${measured.toFixed(1)} LUFS, ${gain >= 0 ? "+" : ""}${gain.toFixed(1)} dB`);
  }
}

const keys = readdirSync(OUT).filter(f => f.endsWith(".mp3") && !f.endsWith(".raw.mp3")).map(f => f.slice(0, -4)).sort();
writeFileSync(path.join(ROOT, "module/sfx-manifest.mjs"),
  "// Generated by tools/gen-sfx.mjs from the files in assets/sfx. Do not edit by hand.\n" +
  `export const SFX_KEYS = new Set(${JSON.stringify(keys, null, 2)});\n`);
console.log(`${keys.length} sound(s) in the manifest.`);
